export type Country = { code: string; name: string; also: string[]; tz: string[] };
export const COUNTRIES: Country[] = COUNTRY_ROWS.map(([code, name, also, tz]) => ({ code, name, also: also ? also.split("|") : [], tz: tz.split(" ") }));
const countryOfTz = new Map<string, Country>();
for (const c of COUNTRIES) for (const tz of c.tz) if (!countryOfTz.has(tz)) countryOfTz.set(tz, c);
/** The country a zone belongs to (null for UTC and the like). */
export const countryOf = (tz: string): Country | null => countryOfTz.get(tz) ?? null;

export type City = { label: string; find: string; tz: string };
export const CITIES: City[] = CITY_ROWS.flatMap(([tz, list]) => list.split(", ").map((find) => ({ label: find.replace(/ \(.*\)$/, ""), find, tz })));
